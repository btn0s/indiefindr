import {build} from 'esbuild';
import {Script} from 'node:vm';
import {readFile,writeFile} from 'node:fs/promises';
const result=await build({entryPoints:['src/mcp-app/view.ts'],bundle:true,write:false,format:'iife',platform:'browser',target:'es2022',minify:true});
const script=result.outputFiles[0].text.replaceAll('</script','<\\/script');
const html=(await readFile('src/mcp-app/template.html','utf8')).replace('__APP_SCRIPT__',()=>script);
new Script(html.slice(html.indexOf('<script>')+8,html.lastIndexOf('</script>')));
await writeFile('src/lib/mcp-app-html.ts','// Generated by scripts/build-mcp-app.mjs.\nexport const APP_HTML='+JSON.stringify(html)+';\n');
